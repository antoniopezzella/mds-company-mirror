#!/usr/bin/env node
/**
 * Self-test for the accessibility gate.
 *
 * WHY THIS EXISTS
 * ---------------
 * The axe gate silently checked nothing for an unknown period. `.storybook/
 * vitest.setup.ts` called `setProjectAnnotations()` manually, and since
 * Storybook 10.3 that makes @storybook/addon-vitest skip its own automatic
 * provisioning — the path that wires in the ADDONS' annotations. So
 * preview.tsx's decorators applied while addon-a11y's never did, and
 * `a11y: { test: 'error' }` ran zero checks while reporting green across every
 * story in the repo. See the comment block at vitest.config.ts:120-128.
 *
 * It was caught by hand, with a probe story carrying deliberate violations
 * that PASSED when it should have failed. That probe was never automated, so
 * the same regression would be just as silent today — a green suite is
 * indistinguishable from a disabled gate unless something asserts otherwise.
 *
 * This script automates that probe: it writes a story with an unambiguous
 * violation, runs it through the real storybook vitest project, and asserts
 * the run FAILS. A passing probe means the gate is dead.
 *
 * The probe is generated and removed rather than committed, because a
 * permanently-violating story would make `npm test` permanently red. It must
 * live under a path .storybook/main.ts indexes — storybookTest discovers
 * stories via Storybook's own indexer, not via a Vitest include glob, so a
 * file outside those globs would simply never run.
 *
 * Usage:  node scripts/check-a11y-gate.js
 * Exit:   0 the gate caught the violation · 1 the gate is not working · 2 harness error
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const probePath = path.join(root, 'src', 'stories', '_health', 'A11yGateProbe.stories.tsx');
const probeRel = path.relative(root, probePath);

// A button with no discernible text, no aria-label and no title. axe's
// `button-name` rule is serious-impact and has no false-negative path: if the
// gate is wired at all, this fails. Deliberately NOT a colour-contrast case —
// contrast depends on resolved tokens and could regress for unrelated reasons.
const PROBE = `// GENERATED by scripts/check-a11y-gate.js — deleted again immediately.
// If you are reading this in a commit, the script crashed; delete the file.
import type { Meta, StoryObj } from '@storybook/react-vite';

const meta: Meta = {
  title: '_health/A11yGateProbe',
  component: () => <button type="button" />,
};
export default meta;

/** Deliberate axe violation: button-name. The gate MUST fail on this. */
export const DeliberateViolation: StoryObj = {
  render: () => <button type="button" />,
};
`;

const cleanup = () => {
  try {
    if (fs.existsSync(probePath)) fs.unlinkSync(probePath);
  } catch (err) {
    console.error(`check-a11y-gate: could not remove ${probeRel}: ${err.message}`);
    console.error('Delete it by hand — a violating story left in place turns the suite red.');
  }
};

process.on('SIGINT', () => { cleanup(); process.exit(2); });
process.on('SIGTERM', () => { cleanup(); process.exit(2); });

let probeFailed;
try {
  fs.writeFileSync(probePath, PROBE);
  try {
    execFileSync(
      'npx',
      ['vitest', 'run', '--project', 'storybook', probeRel],
      { cwd: root, stdio: 'pipe', encoding: 'utf8' }
    );
    probeFailed = false; // vitest exited 0 — the violation was not caught
  } catch (err) {
    // Distinguish "the test failed" (what we want) from "the harness broke".
    const out = `${err.stdout ?? ''}${err.stderr ?? ''}`;
    if (err.status === undefined) throw err;
    const reportedAFailure = /Test Files\s+\d+ failed/.test(out) || /\d+ failed/.test(out);
    // ATTRIBUTION, not just "something went red".
    //
    // Matching only "N failed" made every failure mode look like a healthy
    // gate: a compile error in the generated probe, an addon upgrade changing
    // the Meta shape, a Playwright crash. All of those print "the gate caught
    // it" while axe could be entirely dead — which is precisely the ambiguity
    // this script exists to remove, reproduced one level up.
    const blamedAxe = /button-name/.test(out);
    if (!reportedAFailure || !blamedAxe) {
      console.error(
        reportedAFailure
          ? 'check-a11y-gate: the probe failed, but NOT for the reason it was written.'
          : 'check-a11y-gate: vitest exited non-zero but reported no test failure.'
      );
      console.error(
        reportedAFailure
          ? 'Expected the failure to name axe\'s `button-name` rule. It did not, so this\n' +
            'tells us nothing about whether the gate is alive. Raw output:\n'
          : 'This is a harness problem, not a gate result. Raw output:\n'
      );
      console.error(out.slice(-2000));
      cleanup();
      process.exit(2);
    }
    probeFailed = true;
  }
} catch (err) {
  console.error(`check-a11y-gate: harness error — ${err.message}`);
  cleanup();
  process.exit(2);
} finally {
  cleanup();
}

console.log('\nAccessibility gate self-test\n');
if (probeFailed) {
  console.log('✓ The gate caught a deliberate `button-name` violation.');
  console.log('  addon-a11y annotations are provisioned and axe is running against real stories.');
  process.exit(0);
}

console.error('✗ GATE NOT WORKING — a story with a deliberate axe violation PASSED.');
console.error('');
console.error('  Every green a11y result in this repo is currently meaningless.');
console.error('  Most likely cause: addon-vitest skipped automatic provisioning of preview');
console.error('  annotations, so addon-a11y never wired in and `a11y: { test: "error" }`');
console.error('  in .storybook/preview.tsx checks nothing. That is the exact regression');
console.error('  recorded at vitest.config.ts:120-128 — a manual setProjectAnnotations()');
console.error('  call in a `setupFiles` entry is what caused it last time.');
process.exit(1);
