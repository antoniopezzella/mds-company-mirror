/**
 * Lazy-load GSAP utilities for pages that don't need animations
 * This reduces the initial bundle for non-animated routes
 */

// Dynamic import for GSAP
export const loadGSAP = async () => {
  const { gsap, ensureGsapRegistered } = await import(
    '../pages/marsh-new-charpter-begins/animations/gsap.client'
  );
  ensureGsapRegistered();
  return { gsap };
};

// Dynamic import for ScrollTrigger
export const loadScrollTrigger = async () => {
  const { ScrollTrigger } = await import('gsap/ScrollTrigger');
  return { ScrollTrigger };
};

/**
 * Preload GSAP for smoother animation start
 * Call this on pages that will definitely use animations
 */
export const preloadGSAP = () => {
  // Use link rel="preload" or rel="prefetch"
  const link = document.createElement('link');
  link.rel = 'prefetch';
  link.as = 'script';
  // Note: The actual chunk name will be generated by Vite
  document.head.appendChild(link);
};

/**
 * Hook to conditionally load GSAP based on user preferences
 */
export const useConditionalGSAP = () => {
  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  
  if (prefersReducedMotion) {
    return null; // Don't load GSAP if user prefers reduced motion
  }
  
  return loadGSAP();
};
